const normalizeUsername = (username) =>
  (username || "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9._]/g, "")
    .slice(0, 20);

export const isUsernameAvailable = async (username) => {
  const normalized = normalizeUsername(username);
  if (!/^[a-z0-9._]{3,20}$/.test(normalized)) return false;

  // Check if username is in reserved words list
  if (RESERVED_WORDS.includes(normalized)) return false;

  // Check if username already exists in users collection
  const q = query(collection(db, "users"), where("username", "==", normalized));
  const snapshot = await getDocs(q);
  return snapshot.empty;
};

export const createUserDocWithUsername = async (uid, data, username) => {
  const normalized = normalizeUsername(username);
  if (!/^[a-z0-9._]{3,20}$/.test(normalized)) {
    const err = new Error("Invalid username format");
    err.code = "USERNAME_INVALID";
    throw err;
  }

  // Check if username is reserved
  if (RESERVED_WORDS.includes(normalized)) {
    const err = new Error("Username is reserved and cannot be used");
    err.code = "USERNAME_RESERVED";
    throw err;
  }

  // Check if username is already taken
  const isAvailable = await isUsernameAvailable(normalized);
  if (!isAvailable) {
    const err = new Error("Username already taken");
    err.code = "USERNAME_TAKEN";
    throw err;
  }

  // Create user document with username
  await setDoc(doc(db, "users", uid), {
    ...data,
    username: normalized,
    createdAt: data?.createdAt || new Date().toISOString(),
  });

  return normalized;
};
