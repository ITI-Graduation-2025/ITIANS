// --- User CRUD Operations ---
export const setUser = async (uid, data) => {
  await setDoc(doc(db, "users", uid), { ...data });
};

export const getUser = async (uid) => {
  const userRef = doc(db, "users", uid);
  const snapshot = await getDoc(userRef);
  if (snapshot.exists()) {
    const userData = { id: snapshot.id, ...snapshot.data() };
    if (userData.createdAt && typeof userData.createdAt.toDate === "function") {
      userData.createdAt = userData.createdAt.toDate().toISOString();
    }
    return userData;
  }
  return "User not found";
};

// Get user by username
export const getUserByUsername = async (username) => {
  if (!username) return "Username is required";

  const normalized = username.toLowerCase().trim();
  const q = query(collection(db, "users"), where("username", "==", normalized));
  const snapshot = await getDocs(q);

  if (!snapshot.empty) {
    const userData = { id: snapshot.docs[0].id, ...snapshot.docs[0].data() };
    if (userData.createdAt && typeof userData.createdAt.toDate === "function") {
      userData.createdAt = userData.createdAt.toDate().toISOString();
    }
    return userData;
  }
  return "User not found";
};

export const updateUser = async (uid, data) => {
  await updateDoc(doc(db, "users", uid), data);
};

export const deleteUser = async (uid) => {
  await deleteDoc(doc(db, "users", uid));
  return { id: uid };
};

export const getAllUsers = async () => {
  const snapshot = await getDocs(collection(db, "users"));
  return snapshot.docs.map((doc) => {
    const data = doc.data();

    // Helper function to convert Timestamp to ISO string
    const convertTimestamp = (timestamp) => {
      if (timestamp?.toDate && typeof timestamp.toDate === "function") {
        return timestamp.toDate().toISOString();
      } else if (timestamp?.seconds) {
        // Handle Timestamp objects without toDate method
        return new Date(timestamp.seconds * 1000).toISOString();
      } else if (typeof timestamp === "string") {
        return timestamp;
      }
      return timestamp;
    };

    // Convert all timestamp fields
    const cleanData = {
      id: doc.id,
      ...data,
      createdAt: convertTimestamp(data.createdAt),
      updatedAt: convertTimestamp(data.updatedAt),
      adminActionDate: convertTimestamp(data.adminActionDate),
      fcmTokenUpdatedAt: convertTimestamp(data.fcmTokenUpdatedAt),
    };

    return cleanData;
  });
};

